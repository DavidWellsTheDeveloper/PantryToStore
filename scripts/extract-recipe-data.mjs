#!/usr/bin/env node
// Regenerates app/content/recipe-data.ts from a local `nuxt generate` output.
//
// Why this exists: the curated recipe library is static-first (PRD §7.2/§14). Real
// Spoonacular payload shape lives in the prerendered HTML as Recipe JSON-LD, so we can
// reseed the manifest from a clean build without touching the (rate-limited) API.
// For fresh/extra recipes use scripts/snapshot-recipes.mjs once quota is available.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const OUT = new URL('../app/content/recipe-data.ts', import.meta.url)
const RECIPE_DIR = new URL('../.output/public/recipe/', import.meta.url)

// Common volume/weight words so `displayName`/scaling can split them from the name.
const UNITS = new Set([
  'cup', 'cups', 'tablespoon', 'tablespoons', 'tbsp', 'tbsps',
  'teaspoon', 'teaspoons', 'tsp', 'tsps',
  'ounce', 'ounces', 'oz', 'pound', 'pounds', 'lb', 'lbs',
  'slice', 'slices', 'clove', 'cloves', 'piece', 'pieces',
  'pinch', 'pinches', 'dash', 'dashes', 'dollop', 'dollops',
  'handful', 'handfuls', 'bunch', 'bunches', 'head', 'heads',
  'fillet', 'fillets', 'strip', 'strips', 'stalk', 'stalks',
  'can', 'cans', 'jar', 'jars', 'package', 'packages', 'pkg',
  'box', 'boxes', 'bottle', 'bottles', 'splash', 'drop', 'drops',
  'g', 'kg', 'ml', 'l', 'liter', 'liters', 'quart', 'quarts',
  'gallon', 'gallons', 'inch', 'inches',
])

const FRACTIONS = { 1: 1, 2: 0.5, 3: 0.3333, 4: 0.25 }

function parseAmount(text) {
  // "3", "1.5", "1/4", "1 1/2", "2 lbs"
  const mixed = text.match(/^(\d+)\s+(\d+)\s*\/\s*(\d+)\b/)
  if (mixed) return Number(mixed[1]) + Number(mixed[2]) / Number(mixed[3])
  const single = text.match(/^(\d+)\s*\/\s*(\d+)\b/)
  if (single) return Number(single[1]) / Number(single[2])
  const plain = text.match(/^(\d+(?:\.\d+)?)\b/)
  return plain ? Number(plain[1]) : undefined
}

function parseIngredient(original) {
  const clean = String(original ?? '').trim().replace(/\s+/g, ' ')
  const out = { original: clean }
  if (!clean) return out
  const lead = clean.match(/^([\d\s./]+)\s+([A-Za-z]+)\b(.*)$/)
  if (!lead) return out
  let amount = parseAmount(lead[1].trim())
  if (amount == null) return out
  const unit = lead[2]
  const rest = lead[3].trim().replace(/^[\s.,]+/, '')
  if (!UNITS.has(unit.toLowerCase())) {
    // e.g. "2 large carrots" — unit is a descriptor; keep whole thing as name.
    out.amount = amount
    return out
  }
  out.amount = amount
  out.unit = unit
  out.name = rest
  return out
}

function durationToMinutes(pt) {
  const m = String(pt || '').match(/PT(?:(\d+)H)?(?:(\d+)M)?/)
  if (!m) return undefined
  return (Number(m[1] || 0) * 60) + Number(m[2] || 0)
}

function parseMacros(nutrition) {
  const g = (s) => (s ? Number.parseFloat(s) || undefined : undefined)
  return {
    calories: g(nutrition?.calories),
    protein: g(nutrition?.proteinContent),
    carbs: g(nutrition?.carbohydrateContent),
    fat: g(nutrition?.fatContent),
  }
}

function extractJsonLd(html) {
  const out = []
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try { out.push(JSON.parse(m[1])) } catch { /* skip */ }
  }
  return out
}

function build() {
  if (!existsSync(RECIPE_DIR)) {
    console.error('No .output/public/recipe found — run `nuxt generate` first.')
    process.exit(1)
  }
  const ids = readdirSync(RECIPE_DIR).filter((d) => /^\d+$/.test(d)).sort()
  const recipes = []
  const missing = []

  for (const id of ids) {
    const html = readFileSync(join(RECIPE_DIR.pathname, id, 'index.html'), 'utf8')
    const recipe = extractJsonLd(html).find((x) => x?.['@type'] === 'Recipe')
    if (!recipe) { missing.push(id); continue }

    const ingredients = (recipe.recipeIngredient ?? []).map((orig) => parseIngredient(String(orig)))
    const steps = (recipe.recipeInstructions ?? [])
      .filter((s) => s && typeof s === 'object' && s.text)
      .map((s) => ({ number: Number(s.position) || 1, step: String(s.text) }))
      .sort((a, b) => a.number - b.number)

    recipes.push({
      id: Number(id),
      title: recipe.name,
      image: Array.isArray(recipe.image) ? recipe.image[0] : recipe.image,
      readyInMinutes: durationToMinutes(recipe.totalTime),
      servings: Number(recipe.recipeYield) || undefined,
      extendedIngredients: ingredients,
      analyzedInstructions: steps.length ? [{ steps }] : [],
      macros: parseMacros(recipe.nutrition),
    })
  }

  if (missing.length) console.warn(`Skipped (no Recipe JSON-LD): ${missing.join(', ')}`)
  const body =
    `// Generated by scripts/extract-recipe-data.mjs — DO NOT hand-edit.\n` +
    `// Curated library snapshots (Spoonacular Recipe JSON-LD parsed from a static build).\n` +
    `// Extend/refresh with scripts/snapshot-recipes.mjs when API quota is available.\n\n` +
    `import type { CuratedRecipeData } from './types'\n\n` +
    `export const recipeData: CuratedRecipeData[] = ` +
    JSON.stringify(recipes, null, 2) +
    `\n`
  writeFileSync(OUT, body)
  console.log(`Wrote ${recipes.length} curated recipe snapshots to app/content/recipe-data.ts`)
}

build()